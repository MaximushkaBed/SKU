def _ensure_topic(db, subject_id: int, topic_name: str, difficulty_level: int) -> Topic:
    topic = db.query(Topic).filter(Topic.subject_id == subject_id, Topic.name == topic_name).first()
    if topic:
        if topic.difficulty_level != difficulty_level:
            topic.difficulty_level = difficulty_level
        return topic

    topic = Topic(subject_id=subject_id, name=topic_name, difficulty_level=difficulty_level)
    db.add(topic)
    db.flush()
    return topic


def _ensure_answers(db, question_id: int, answers_data: list[tuple[str, bool]]) -> None:
    expected_map = {answer_text: is_correct for answer_text, is_correct in answers_data}
    existing_answers = db.query(Answer).filter(Answer.question_id == question_id).all()
    for answer in existing_answers:
        if answer.answer_text not in expected_map:
            db.delete(answer)

    existing_by_text = {
        answer.answer_text: answer
        for answer in db.query(Answer).filter(Answer.question_id == question_id).all()
    }
    for answer_text, is_correct in answers_data:
        existing = existing_by_text.get(answer_text)
        if existing:
            if existing.is_correct != is_correct:
                existing.is_correct = is_correct
            continue
        db.add(Answer(question_id=question_id, answer_text=answer_text, is_correct=is_correct))


def _ensure_question(
    db,
    topic_id: int,
    question_text: str,
    answers_data: list[tuple[str, bool]],
    difficulty: int,
) -> None:
    question = (
        db.query(Question)
        .filter(Question.topic_id == topic_id, Question.question_text == question_text)
        .first()
    )
    if not question:
        question = Question(
            topic_id=topic_id,
            question_text=question_text,
            question_type="single",
            difficulty=difficulty,
        )
        db.add(question)
        db.flush()
    else:
        question.question_type = "single"
        question.difficulty = difficulty

    _ensure_answers(db, question.id, answers_data)


def ensure_default_tests():
    """
    Создаёт и дополняет тесты так, чтобы по каждому предмету было
    не менее 10 тем, а в каждой теме — не менее 20 вопросов.

    Логика:
    - Для каждого предмета создаём/обновляем 10 тем:
      первые EASY_TOPICS_COUNT тем считаем базовыми (difficulty 1),
      остальные — продвинутыми (difficulty 4).
    - Если для предмета в SUBJECT_TEST_BANK описаны «ручные» вопросы
      (quick/full), то:
        * quick-вопросы попадают в первую тему (базовая),
        * full-вопросы — в шестую тему (первая продвинутая),
      но не более QUESTIONS_PER_TOPIC на тему.
    - Остальные недостающие вопросы в каждой теме догенерируются
      шаблонными тренировочными вопросами.
    """
    db = SessionLocal()
    try:
        subjects = db.query(Subject).order_by(Subject.id).all()
        for subject in subjects:
            subject_bank = SUBJECT_TEST_BANK.get(subject.name)
            # 1. Создаём 10 тем для предмета.
            topics: list[tuple[Topic, int]] = []
            for index in range(1, TOPICS_PER_SUBJECT + 1):
                if index <= EASY_TOPICS_COUNT:
                    difficulty_level = 1
                else:
                    difficulty_level = 4
                topic_name = f"Тема {index} ({subject.name})"
                topic = _ensure_topic(db, subject.id, topic_name, difficulty_level)
                topics.append((topic, difficulty_level))

            if subject_bank:
                training_questions = (
                    db.query(Question)
                    .join(Topic, Question.topic_id == Topic.id)
                    .filter(
                        Topic.subject_id == subject.id,
                        Question.question_text.like("%тренировочный вопрос%"),
                    )
                    .all()
                )
                for question in training_questions:
                    db.delete(question)

            # 2. Если есть ручной банк вопросов — раскладываем его:
            #    quick -> первая тема, full -> шестая тема (первая сложная).
            if subject_bank:
                quick_questions = subject_bank.get("quick") or []
                full_questions = subject_bank.get("full") or []

                # Первая тема (базовая) — quick
                first_topic, first_topic_difficulty = topics[0]
                for question_text, answers_data in quick_questions[:QUESTIONS_PER_TOPIC]:
                    _ensure_question(
                        db,
                        first_topic.id,
                        question_text,
                        answers_data,
                        first_topic_difficulty,
                    )

                # Шестая тема (если есть) — full
                if len(topics) >= EASY_TOPICS_COUNT + 1:
                    sixth_topic, sixth_topic_difficulty = topics[EASY_TOPICS_COUNT]
                    for question_text, answers_data in full_questions[:QUESTIONS_PER_TOPIC]:
                        _ensure_question(
                            db,
                            sixth_topic.id,
                            question_text,
                            answers_data,
                            sixth_topic_difficulty,
                        )

            # 3. Догенерируем недостающие вопросы до QUESTIONS_PER_TOPIC в каждой теме
            #    только для предметов без ручного банка.
            if not subject_bank:
                for index, (topic, difficulty_level) in enumerate(topics, start=1):
                    existing_questions = (
                        db.query(Question).filter(Question.topic_id == topic.id).all()
                    )
                    already = len(existing_questions)
                    if already >= QUESTIONS_PER_TOPIC:
                        continue

                    for n in range(already + 1, QUESTIONS_PER_TOPIC + 1):
                        question_text = (
                            f"Тема {index} · {subject.name}: тренировочный вопрос {n}"
                        )
                        answers_data = [
                            (f"Правильный ответ для вопроса {n}", True),
                            (f"Неправильный ответ 1 для вопроса {n}", False),
                            (f"Неправильный ответ 2 для вопроса {n}", False),
                            (f"Неправильный ответ 3 для вопроса {n}", False),
                        ]
                        _ensure_question(
                            db,
                            topic.id,
                            question_text,
                            answers_data,
                            difficulty_level,
                        )

        db.commit()
    finally:
        db.close()
